    #[test]
    fn emit_substitutes_first_layer_bounding_box_into_start_gcode() {
        use crate::toolpath::Segment;
        use glam::DVec3;

        // Two "layers" (distinguished by `Segment::order`): layer 0 spans
        // a 10x10 square, layer 1 (order 1.0, printed after) spans a wider
        // 20x20 square. The bounding box substituted into start_gcode must
        // reflect only the *first* layer (order 0.0), proving the bounds
        // are derived from `Segment::order` rather than from every point in
        // `paths`.
        let paths = vec![
            Path {
                points: vec![DVec3::new(0.0, 0.0, 0.0), DVec3::new(10.0, 10.0, 0.0)],
                segments: vec![Segment {
                    kind: MoveKind::WallOuter,
                    order: 0.0,
                    ..Segment::default()
                }],
                tool: ToolId(0),
            },
            Path {
                points: vec![DVec3::new(-5.0, -5.0, 0.25), DVec3::new(20.0, 20.0, 0.25)],
                segments: vec![Segment {
                    kind: MoveKind::WallOuter,
                    order: 1.0,
                    ..Segment::default()
                }],
                tool: ToolId(0),
            },
        ];
        let config = SlicerConfig {
            start_gcode: "PRINT_START PRINT_MIN={print_min_x},{print_min_y} PRINT_MAX={print_max_x},{print_max_y}"
                .to_string(),
            end_gcode: "PRINT_END".to_string(),
            ..SlicerConfig::default()
        };

        let out = emit(&paths, &config);

        assert!(out.contains("PRINT_START PRINT_MIN=0.000,0.000 PRINT_MAX=10.000,10.000"));
        assert!(out.trim_end().ends_with("PRINT_END"));
    }

    #[test]
    fn emit_writes_f_reflecting_segment_speed_and_omits_it_when_unchanged() {
        use crate::toolpath::Segment;
        use glam::DVec3;

        // Three consecutive incoming segments: the first two share a speed
        // (F should only be emitted once, on the first), the third has a
        // different speed (F should be emitted again).
        let paths = vec![Path {
            points: vec![
                DVec3::new(0.0, 0.0, 0.0),
                DVec3::new(1.0, 0.0, 0.0),
                DVec3::new(2.0, 0.0, 0.0),
                DVec3::new(3.0, 0.0, 0.0),
            ],
            segments: vec![
                Segment {
                    kind: MoveKind::WallOuter,
                    speed: 3000.0,
                    ..Segment::default()
                },
                Segment {
                    kind: MoveKind::WallOuter,
                    speed: 3000.0,
                    ..Segment::default()
                },
                Segment {
                    kind: MoveKind::Travel,
                    speed: 9000.0,
                    ..Segment::default()
                },
            ],
            tool: ToolId(0),
        }];

        let out = emit(&paths, &config_without_print_gcode());
        let move_lines: Vec<&str> = out
            .lines()
            .filter(|line| line.starts_with("G0 ") || line.starts_with("G1 "))
            .collect();

        // First move (i == 0) is a plain positioning move with no incoming
        // segment, so it never carries an F.
        assert!(!move_lines[0].contains('F'));
        // Second move's incoming segment (speed 3000.0) has no prior F to
        // compare against, so F is emitted.
        assert!(move_lines[1].contains("F3000.000"));
        // Third move's incoming segment shares the same speed (3000.0) as
        // the previous emitted F, so F must be omitted entirely.
        assert!(!move_lines[2].contains('F'));
        // Fourth move's incoming segment has a different speed (9000.0), so
        // F is emitted again.
        assert!(move_lines[3].contains("F9000.000"));
    }

