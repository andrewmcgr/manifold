//! Gcode emission from planned toolpaths.

use crate::{
    toolpath::{MoveKind, Path},
    SlicerConfig,
};

/// Render toolpaths to a Gcode program string.
///
/// Inserts a tool-select line (`T{n}`) whenever consecutive paths are
/// assigned to different tools, followed by `G92 E0` to reset that tool's
/// filament position — each tool is tracked as its own independent
/// extruder, so a fresh tool-select always restarts extrusion accounting
/// from zero rather than carrying over the previous tool's total. Uses
/// absolute extrusion mode (`M82`, the common firmware default): each
/// extruding move's `E` value is `Segment::extrusion_length` accumulated
/// onto a running per-tool total (see `toolpath::plan`, which finalizes
/// `extrusion_length` from segment geometry, line width, and the tool's
/// `extrusion_multiplier`), not emitted as a per-move delta. Prime/purge
/// Gcode around tool changes is not implemented yet — follow-up work, see
/// ROADMAP.md Phase 2.
pub fn emit(paths: &[Path], config: &SlicerConfig) -> String {
    let mut out = String::new();
    out.push_str("; generated by manifold-core\n");
    out.push_str(&format!("; layer_height={}\n", config.layer_height));

    let mut current_tool = None;
    let mut current_e = 0.0;

    for path in paths {
        if current_tool != Some(path.tool) {
            out.push_str(&format!("T{}\n", path.tool));
            out.push_str("G92 E0\n");
            current_tool = Some(path.tool);
            current_e = 0.0;
        }

        for (i, p) in path.points.iter().enumerate() {
            // `segments[i]` describes the edge `points[i] -> points[i + 1]`
            // (see `toolpath::Path`'s contract), so the move *arriving* at
            // `points[i]` (i >= 1) is `segments[i - 1]`, not `segments[i]`.
            // The very first point has no incoming edge - it's always a
            // plain positioning move (G0).
            let incoming_segment = if i > 0 {
                path.segments.get(i - 1)
            } else {
                None
            };
            let extruding =
                incoming_segment.is_some_and(|segment| segment.kind != MoveKind::Travel);
            let cmd = if i == 0 || !extruding { "G0" } else { "G1" };
            out.push_str(&format!("{cmd} X{:.3} Y{:.3} Z{:.3}", p.x, p.y, p.z));
            if extruding {
                current_e += incoming_segment.map_or(0.0, |segment| segment.extrusion_length);
                out.push_str(&format!(" E{current_e:.5}"));
            }
            out.push('\n');
        }
    }

    out
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::ids::ToolId;

    #[test]
    fn emit_inserts_tool_change_between_differing_tools() {
        let paths = vec![
            Path {
                points: Vec::new(),
                segments: Vec::new(),
                tool: ToolId(0),
            },
            Path {
                points: Vec::new(),
                segments: Vec::new(),
                tool: ToolId(1),
            },
            Path {
                points: Vec::new(),
                segments: Vec::new(),
                tool: ToolId(1),
            },
        ];

        let out = emit(&paths, &SlicerConfig::default());

        assert_eq!(out.matches("T0\n").count(), 1);
        assert_eq!(out.matches("T1\n").count(), 1);
    }

    #[test]
    fn emit_omits_tool_line_when_no_paths() {
        let out = emit(&[], &SlicerConfig::default());
        assert!(!out.contains('T'));
    }

    #[test]
    fn emit_derives_g0_g1_from_segment_kind() {
        use crate::toolpath::Segment;
        use glam::DVec3;

        // A single path: first point is always the travel move (G0).
        // `segments[i]` describes the edge `points[i] -> points[i + 1]`, so
        // the move arriving at `points[1]` is governed by `segments[0]`
        // (WallOuter -> G1) and the move arriving at `points[2]` is
        // governed by `segments[1]` (Travel -> G0) — proving the command
        // derives from the *incoming* segment's kind rather than position
        // alone.
        let paths = vec![Path {
            points: vec![
                DVec3::new(0.0, 0.0, 0.0),
                DVec3::new(1.0, 0.0, 0.0),
                DVec3::new(2.0, 0.0, 0.0),
            ],
            segments: vec![
                Segment {
                    kind: MoveKind::WallOuter,
                    ..Segment::default()
                },
                Segment {
                    kind: MoveKind::Travel,
                    ..Segment::default()
                },
                Segment {
                    kind: MoveKind::WallOuter,
                    ..Segment::default()
                },
            ],
            tool: ToolId(0),
        }];

        let out = emit(&paths, &SlicerConfig::default());
        let commands: Vec<&str> = out
            .lines()
            .filter(|line| line.starts_with("G0") || line.starts_with("G1"))
            .map(|line| &line[..2])
            .collect();

        assert_eq!(commands, vec!["G0", "G1", "G0"]);
    }

    #[test]
    fn emit_accumulates_absolute_e_across_extruding_segments_and_omits_it_for_travel() {
        use crate::toolpath::Segment;
        use glam::DVec3;

        let paths = vec![Path {
            points: vec![
                DVec3::new(0.0, 0.0, 0.0),
                DVec3::new(1.0, 0.0, 0.0),
                DVec3::new(2.0, 0.0, 0.0),
            ],
            segments: vec![
                Segment {
                    kind: MoveKind::WallOuter,
                    extrusion_length: 1.5,
                    ..Segment::default()
                },
                Segment {
                    kind: MoveKind::Travel,
                    extrusion_length: 0.0,
                    ..Segment::default()
                },
                Segment {
                    kind: MoveKind::WallOuter,
                    extrusion_length: 2.5,
                    ..Segment::default()
                },
            ],
            tool: ToolId(0),
        }];

        let out = emit(&paths, &SlicerConfig::default());
        let lines: Vec<&str> = out.lines().collect();

        // lines[0..=1] are header comments, lines[2] is "T0", lines[3] is
        // "G92 E0"; the three point-moves follow at lines[4..=6].
        // First point: plain travel, no E.
        assert!(lines[4].starts_with("G0") && !lines[4].contains('E'));
        // Second point: extruding move, E accumulates the first segment's
        // extrusion_length (1.5).
        assert!(lines[5].starts_with("G1") && lines[5].contains("E1.50000"));
        // Third point: a Travel segment interrupted extrusion, so this move
        // is G0 and carries no E, but the running total is preserved for
        // the *next* extruding move rather than reset.
        assert!(lines[6].starts_with("G0") && !lines[6].contains('E'));
    }

    #[test]
    fn emit_resets_e_to_zero_on_tool_change() {
        use crate::toolpath::Segment;
        use glam::DVec3;

        let paths = vec![
            Path {
                points: vec![DVec3::new(0.0, 0.0, 0.0), DVec3::new(1.0, 0.0, 0.0)],
                segments: vec![Segment {
                    kind: MoveKind::WallOuter,
                    extrusion_length: 5.0,
                    ..Segment::default()
                }],
                tool: ToolId(0),
            },
            Path {
                points: vec![DVec3::new(0.0, 0.0, 0.0), DVec3::new(1.0, 0.0, 0.0)],
                segments: vec![Segment {
                    kind: MoveKind::WallOuter,
                    extrusion_length: 1.0,
                    ..Segment::default()
                }],
                tool: ToolId(1),
            },
        ];

        let out = emit(&paths, &SlicerConfig::default());

        assert_eq!(out.matches("G92 E0").count(), 2);
        assert!(out.contains("E5.00000"));
        // The second tool's extrusion starts fresh from zero rather than
        // continuing tool 0's running total of 5.0.
        assert!(out.contains("E1.00000"));
        assert!(!out.contains("E6.00000"));
    }
}
